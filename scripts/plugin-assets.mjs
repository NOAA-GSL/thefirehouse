#!/usr/bin/env node
/**
 * Writes the plugin's icons, logos, link-preview image and search module from the
 * site's own.
 *
 *   node scripts/plugin-assets.mjs           write them
 *   node scripts/plugin-assets.mjs --check   fail if the committed copies are out of date
 *
 * - `wp-content/plugins/firehouse/assets/icons/icons.php`: every icon in the site's
 *   registry (`ICON_NAMES` in src/design-system/Icon.tsx), drawn by the site's own
 *   `Icon` component through Vite, as one PHP array of SVG by name. The plugin inlines
 *   them from it (includes/class-icons.php); with opcache on, the array stays compiled
 *   and a request reads no file for its icons (WORDPRESS-PLAN.md, Phase 4's weight).
 *   The drawing inside is exactly what the site renders; only the outer <svg> changes.
 *   It drops what belongs to one use of an icon (class, style, `aria-hidden`,
 *   `focusable`) and keeps Lucide's 24×24 size, which the plugin replaces with each
 *   use's size where it inlines the icon, as `Icon` does. Each icon must hold only what
 *   shared/icon-svg.json allows. tests/IconsTest.php checks that again on the file that
 *   ships, and that the file holds nothing but its header and string literals, since
 *   the plugin runs it. Lucide's licence goes beside it as LICENSE.txt.
 * - `wp-content/plugins/firehouse/assets/logos/`: the images `BrandMark` imports,
 *   read from the component and copied unchanged. The NOAA and GSL logos stay with the
 *   static build; GSL's header carries its own.
 * - `wp-content/plugins/firehouse/assets/search/search.js`: the site's search
 *   (src/content/search.ts), bundled as one ES module for the explorer's view script,
 *   so the browser lists what the site lists (searchModule() below).
 * - `wp-content/plugins/firehouse/assets/preview/og-image.png`: the site's link-preview
 *   image (`public/og-image.png`), copied unchanged, which Firehouse pages name in their
 *   Open Graph tags (includes/class-head.php).
 *
 * Each folder holds exactly these files, so a file the script stops writing goes too
 * (a logo `BrandMark` drops, or an icon file from before the array).
 */

import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { createServer } from 'vite';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS = resolve(ROOT, 'wp-content/plugins/firehouse/assets');
const RULES = JSON.parse(readFileSync(resolve(ROOT, 'wp-content/plugins/firehouse/shared/icon-svg.json'), 'utf8'));

/**
 * What in an icon's SVG falls outside shared/icon-svg.json: an element, attribute or
 * value it doesn't allow, or anything that isn't a tag (text, a comment, CDATA).
 */
function iconProblems(svg) {
  const problems = [];
  const value = new RegExp(RULES.value);
  const rest = svg.replace(/<\/?([^\s/>]+)((?:\s+[^\s=>]+="[^"]*")*)\s*\/?>/g, (tag, element, attributes) => {
    if (!RULES.elements.includes(element)) problems.push(`<${element}>`);
    for (const [, name, text] of attributes.matchAll(/\s+([^\s=>]+)="([^"]*)"/g)) {
      if (!RULES.attributes.includes(name)) problems.push(`${element} ${name}`);
      else if (name === 'xmlns' ? text !== RULES.namespace : !value.test(text)) problems.push(`${element} ${name}="${text}"`);
    }
    return '';
  });
  if (rest.trim()) problems.push(`text outside the tags: ${rest.trim().slice(0, 60)}`);
  if (!svg.startsWith('<svg ')) problems.push('it doesn’t start with <svg>');
  return problems;
}
/** A PHP string literal. Single-quoted, so only a backslash and the quote need escaping. */
const phpString = (text) => `'${text.replace(/[\\']/g, '\\$&')}'`;

/**
 * The icons as the PHP file the plugin reads: a header, then one array of string
 * literals, sorted by name and laid out as WordPress's coding standards ask.
 */
function iconsPhp(icons) {
  const sorted = [...icons].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const width = Math.max(...sorted.map(([name]) => phpString(name).length));
  const entries = sorted.map(([name, svg]) => `\t${phpString(name).padEnd(width)} => ${phpString(svg)},`);
  return `<?php
/**
 * The site's icons, by name, as includes/class-icons.php inlines them. Generated by
 * scripts/plugin-assets.mjs, which draws each with the site's own \`Icon\` component:
 * don't edit this file; change src/, then run \`npm run plugin:assets\`.
 *
 * Each holds only what shared/icon-svg.json allows (tests/IconsTest.php). The icons
 * are Lucide's, under the ISC License in LICENSE.txt beside this file.
 *
 * @package Firehouse
 */

declare( strict_types = 1 );

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

return array(
${entries.join('\n')}
);
`;
}

// The images BrandMark imports, read from the component so a new one comes along, in
// whatever format it is. tests/LogosTest.php checks every logo the plugin's PHP names is
// among them.
const LOGOS = [...readFileSync(resolve(ROOT, 'src/design-system/BrandMark.tsx'), 'utf8').matchAll(/from '\.\.\/assets\/logos\/([\w.-]+\.\w+)'/g)].map(
  ([, name]) => name,
);
if (LOGOS.length === 0) throw new Error('BrandMark.tsx imports no logo, so there is nothing to copy.');

/** Every file this script owns, by its path under assets/. */
const files = new Map();

// Vite's dependency cache goes in a folder of its own, removed afterwards, so this
// never writes into node_modules/.vite, which `npm run dev` uses.
const cacheDir = mkdtempSync(join(tmpdir(), 'firehouse-assets-'));
const server = await createServer({
  root: ROOT,
  configFile: resolve(ROOT, 'vite.config.ts'),
  cacheDir,
  logLevel: 'error',
  appType: 'custom',
  server: { middlewareMode: true, hmr: false, watch: null },
});
try {
  const { Icon, ICON_NAMES } = await server.ssrLoadModule('/src/design-system/Icon.tsx');
  const { createElement } = await import('react');
  const { renderToStaticMarkup } = await import('react-dom/server');
  const icons = [];
  for (const name of ICON_NAMES) {
    if (!new RegExp(RULES.name).test(name)) throw new Error(`"${name}" isn't an icon name shared/icon-svg.json allows.`);
    const rendered = renderToStaticMarkup(createElement(Icon, { name, size: 24 }));
    // Only the outer <svg> loses its per-use attributes: a <rect> inside needs its size.
    const svg = rendered.replace(/^<svg[^>]*>/, (tag) => tag.replace(/ (?:class|style|aria-hidden|focusable)="[^"]*"/g, ''));
    const drawing = (markup) => markup.slice(markup.indexOf('>') + 1);
    if (drawing(svg) !== drawing(rendered)) throw new Error(`The ${name} icon's drawing changed on its way to the file.`);
    const problems = iconProblems(svg);
    if (problems.length) throw new Error(`The ${name} icon holds what shared/icon-svg.json doesn't allow: ${problems.join('; ')}`);
    icons.push([name, svg]);
  }
  files.set('icons/icons.php', Buffer.from(iconsPhp(icons)));
} finally {
  await server.close();
  rmSync(cacheDir, { recursive: true, force: true });
}
// Lucide's licence asks for its notice in every copy of the icons.
files.set('icons/LICENSE.txt', readFileSync(resolve(ROOT, 'node_modules/lucide-react/LICENSE')));
for (const name of LOGOS) files.set(`logos/${name}`, readFileSync(resolve(ROOT, 'src/assets/logos', name)));
files.set('preview/og-image.png', readFileSync(resolve(ROOT, 'public/og-image.png')));
files.set('search/search.js', Buffer.from(await searchModule()));

/**
 * The site's search (src/content/search.ts, with effectiveRegions() from derive.ts, which
 * counts a national study in every GACC, and the vocabulary they read) as one ES module, for the explorer's view script: the same code the
 * site runs, held to shared/cases/search.json by Vitest, so the browser lists what the
 * site lists. Bundled by esbuild, not minified, so a review reads it.
 */
async function searchModule() {
  const { build } = await import('esbuild');
  const result = await build({
    stdin: {
      contents: [
        "export { activeFacetCount, effectiveSort, facetCounts, filterProjects, scores, serializeProjectQuery, MAX_TERMS } from './search';",
        "export { effectiveRegions } from './derive';",
      ].join('\n'),
      resolveDir: resolve(ROOT, 'src/content'),
      sourcefile: 'search-module.ts',
      loader: 'ts',
    },
    absWorkingDir: ROOT,
    bundle: true,
    format: 'esm',
    target: 'es2020',
    platform: 'browser',
    charset: 'utf8',
    legalComments: 'inline',
    write: false,
    banner: {
      js: '/* The explorer\'s search, generated by scripts/plugin-assets.mjs from src/content/search.ts and\n   derive.ts. Don\'t edit: change those, then run `npm run plugin:assets`. */',
    },
  });
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

const folders = [...new Set([...files.keys()].map((path) => path.split('/')[0]))];

/** Text files compare without regard to line endings, which a checkout may change. */
function sameFile(present, expected, path) {
  if (!/\.(?:php|txt|js)$/.test(path)) return present.equals(expected);
  const text = (bytes) => bytes.toString('utf8').replace(/\r\n/g, '\n');
  return text(present) === text(expected);
}

if (process.argv.includes('--check')) {
  const stale = [];
  for (const folder of folders) {
    let present = [];
    try {
      present = readdirSync(resolve(ASSETS, folder)).map((name) => `${folder}/${name}`);
    } catch {
      // A missing folder is out of date.
    }
    for (const path of present) if (!files.has(path)) stale.push(`${path} shouldn't be there`);
    for (const [path, bytes] of files) {
      if (!path.startsWith(`${folder}/`)) continue;
      if (!present.includes(path)) stale.push(`${path} is missing`);
      else if (!sameFile(readFileSync(resolve(ASSETS, path)), bytes, path)) stale.push(`${path} differs`);
    }
  }
  if (stale.length) {
    console.error(`The plugin's icons, logos and preview image are out of date with the site's:\n  ${stale.join('\n  ')}\nRun: npm run plugin:assets`);
    process.exit(1);
  }
  console.log(`Icons, logos and the preview image are up to date: ${files.size} files.`);
} else {
  for (const folder of folders) {
    rmSync(resolve(ASSETS, folder), { recursive: true, force: true });
    mkdirSync(resolve(ASSETS, folder), { recursive: true });
  }
  for (const [path, bytes] of files) writeFileSync(resolve(ASSETS, path), bytes);
  console.log(`Wrote ${files.size} files in ${folders.map((folder) => `assets/${folder}/`).join(' and ')}.`);
}
